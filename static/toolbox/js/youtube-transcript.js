/**
 * YouTube transcript fetcher via Cloudflare Workers proxy.
 */
(function initToolboxYoutubeTranscript(global) {
  "use strict";

  const PROXY_BASE_URL = "https://vibe-speak-proxy.kishineseiichi.workers.dev/";
  const SAME_ORIGIN_TRANSCRIPT_URL = "/toolbox/api/youtube-transcript";
  // 学校などのネットワークが *.workers.dev を直接ブロックしているケース向けに、
  // Render（同一オリジン）経由で Cloudflare Worker を代理呼び出しする中継エンドポイント。
  // ブラウザからは常に同一オリジンにしか見えないので、Worker 自体のドメインが
  // フィルタされていても Cloudflare 側の良好な IP 経由で字幕を取得できる。
  const SAME_ORIGIN_WORKER_RELAY_URL = "/toolbox/api/youtube-transcript-worker";
  const LOCAL_CACHE_PREFIX = "toolboxCnn10YoutubeTranscript:v1:";
  const LOCAL_CACHE_TTL_MS = 7 * 24 * 60 * 60 * 1000;
  const VIDEO_ID_RE = /^[a-zA-Z0-9_-]{11}$/;
  const DEFAULT_LANGUAGES = ["en", "ja"];
  const DEFAULT_TIMEOUT_MS = 20000;
  const DEFAULT_MAX_RETRIES = 4;
  const LANGUAGE_LABELS = { ja: "Japanese", en: "English" };

  function extractVideoId(input) {
    const raw = String(input || "").trim();
    if (!raw) throw new Error("YouTube URL または動画 ID を入力してください。");
    if (VIDEO_ID_RE.test(raw)) return raw;

    const decoded = decodeURIComponent(raw.split("#")[0]);
    const match = decoded.match(/(?:v=|vi=|\/)([0-9A-Za-z_-]{11})(?=$|[^0-9A-Za-z_-])/i);
    if (match && VIDEO_ID_RE.test(match[1])) return match[1];

    throw new Error(
      "有効な YouTube URL または 11 桁の動画 ID を入力してください。（watch?v= / youtu.be/ / shorts/ に対応）"
    );
  }

  function languageLabel(code) {
    const base = String(code || "").split("-")[0].toLowerCase();
    return LANGUAGE_LABELS[base] || code || "Unknown";
  }

  function langMatches(candidate, preferred) {
    const c = String(candidate || "").toLowerCase();
    const p = String(preferred || "").toLowerCase();
    return c === p || c.startsWith(`${p}-`);
  }

  function normalizeSnippet(snippet) {
    const text = String(snippet?.text || snippet?.content || "").trim();
    if (!text) return null;

    let start = Number(snippet.start ?? snippet.startSec ?? snippet.offset ?? 0);
    let duration = Number(snippet.duration ?? snippet.dur ?? snippet.length ?? 0);

    if (snippet.start_ms != null || snippet.tStartMs != null) {
      start = Number(snippet.start_ms ?? snippet.tStartMs ?? 0) / 1000;
    }
    if (snippet.d_duration_ms != null || snippet.dDurationMs != null) {
      duration = Number(snippet.d_duration_ms ?? snippet.dDurationMs ?? 0) / 1000;
    }

    return {
      start: Math.round(start * 1000) / 1000,
      duration: Math.round(Math.max(duration, 0.1) * 1000) / 1000,
      text,
    };
  }

  function normalizeSnippets(snippets) {
    return (snippets || []).map(normalizeSnippet).filter(Boolean);
  }

  function parseTimedTextEvents(data) {
    const snippets = [];
    for (const event of data?.events || []) {
      if (!event?.segs) continue;
      const text = event.segs
        .map((seg) => seg.utf8 || "")
        .join("")
        .replace(/\n/g, " ")
        .trim();
      if (!text) continue;
      snippets.push({
        start: Number(event.tStartMs || 0) / 1000,
        duration: Math.max(Number(event.dDurationMs || 0) / 1000, 0.1),
        text,
      });
    }
    return snippets;
  }

  function parseScrapingBeeRuns(entry) {
    const runs = entry?.snippet?.runs || [];
    return runs
      .map((run) => String(run?.text || "").trim())
      .filter(Boolean)
      .join(" ");
  }

  function parseScrapingBeeEntries(entries) {
    return (entries || [])
      .map((entry) =>
        normalizeSnippet({
          start_ms: entry.start_ms,
          d_duration_ms: entry.d_duration_ms,
          text: parseScrapingBeeRuns(entry),
        })
      )
      .filter(Boolean);
  }

  function pickScrapingBeeTrack(subtitlesRoot, languages) {
    const manual = subtitlesRoot?.uploader_provided || {};
    const automatic = subtitlesRoot?.auto_generated || {};

    for (const lang of languages) {
      if (manual[lang]?.length) return { languageCode: lang, isGenerated: false, snippets: parseScrapingBeeEntries(manual[lang]) };
      for (const [key, entries] of Object.entries(manual)) {
        if (langMatches(key, lang) && entries?.length) {
          return { languageCode: key, isGenerated: false, snippets: parseScrapingBeeEntries(entries) };
        }
      }
    }

    for (const lang of languages) {
      if (automatic[lang]?.length) return { languageCode: lang, isGenerated: true, snippets: parseScrapingBeeEntries(automatic[lang]) };
      for (const [key, entries] of Object.entries(automatic)) {
        if (langMatches(key, lang) && entries?.length) {
          return { languageCode: key, isGenerated: true, snippets: parseScrapingBeeEntries(entries) };
        }
      }
    }

    return null;
  }

  function selectCaptionTrack(tracks, preferredLanguages, includeAutoGenerated) {
    if (!tracks?.length) return null;
    const manual = tracks.filter((track) => track.kind !== "asr");
    const auto = tracks.filter((track) => track.kind === "asr");
    const searchOrder = includeAutoGenerated ? [...manual, ...auto] : manual;

    for (const lang of preferredLanguages) {
      const exact = searchOrder.find((track) => langMatches(track.languageCode, lang));
      if (exact) return exact;
    }
    return searchOrder[0] || null;
  }

  function parseCaptionTrackEvents(track) {
    if (Array.isArray(track?.events)) return parseTimedTextEvents(track);
    if (Array.isArray(track?.snippets)) return normalizeSnippets(track.snippets);
    if (Array.isArray(track?.segments)) return normalizeSnippets(track.segments);
    return [];
  }

  function decodeXmlEntities(text) {
    return String(text || "")
      .replace(/&amp;/g, "&")
      .replace(/&lt;/g, "<")
      .replace(/&gt;/g, ">")
      .replace(/&quot;/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/&apos;/g, "'")
      .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
      .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(parseInt(dec, 10)));
  }

  function parseTimedTextXml(xml) {
    const results = [];
    const pRegex = /<p\b([^>]*)>([\s\S]*?)<\/p>/g;
    const sRegex = /<s[^>]*>([^<]*)<\/s>/g;
    let match;
    while ((match = pRegex.exec(xml || "")) !== null) {
      const attrs = match[1] || "";
      const tMatch = attrs.match(/\bt="(\d+)"/);
      const dMatch = attrs.match(/\bd="(\d+)"/);
      if (!tMatch || !dMatch) continue;
      const startMs = parseInt(tMatch[1], 10);
      const durMs = parseInt(dMatch[1], 10);
      const inner = match[2] || "";
      let text = "";
      let sMatch;
      sRegex.lastIndex = 0;
      while ((sMatch = sRegex.exec(inner)) !== null) {
        text += sMatch[1];
      }
      if (!text) text = inner.replace(/<[^>]+>/g, "");
      text = decodeXmlEntities(text).trim();
      if (text) {
        results.push({
          start: Math.round((startMs / 1000) * 1000) / 1000,
          duration: Math.round(Math.max(durMs / 1000, 0.1) * 1000) / 1000,
          text,
        });
      }
    }
    if (results.length) return results;

    const classicRegex = /<text start="([^"]*)" dur="([^"]*)">([^<]*)<\/text>/g;
    while ((match = classicRegex.exec(xml || "")) !== null) {
      const text = decodeXmlEntities(match[3]).trim();
      if (!text) continue;
      results.push({
        start: Math.round(parseFloat(match[1]) * 1000) / 1000,
        duration: Math.round(Math.max(parseFloat(match[2]), 0.1) * 1000) / 1000,
        text,
      });
    }
    return results;
  }

  async function snippetsFromTimedTextBody(rawText) {
    const trimmed = String(rawText || "").trim();
    if (!trimmed) return [];
    if (trimmed.startsWith("{")) {
      try {
        const data = JSON.parse(trimmed);
        if (Array.isArray(data?.snippets) && data.snippets.length) {
          return normalizeSnippets(data.snippets);
        }
        if (data?.events) return normalizeSnippets(parseTimedTextEvents(data));
      } catch (_err) {
        /* fall through to XML */
      }
    }
    return normalizeSnippets(parseTimedTextXml(trimmed));
  }

  async function fetchTimedTextInBrowser(tracks, languages) {
    const selected = selectCaptionTrack(tracks, languages, true);
    if (!selected?.baseUrl) {
      throw new Error("日本語・英語の字幕が見つかりませんでした。");
    }
    const timedTextUrls = [
      selected.baseUrl,
      `${PROXY_BASE_URL}?timedtext=${encodeURIComponent(selected.baseUrl)}`,
      `${SAME_ORIGIN_TRANSCRIPT_URL.replace(/youtube-transcript$/, "youtube-timedtext")}?url=${encodeURIComponent(selected.baseUrl)}`,
    ];
    let lastError = null;
    for (const url of timedTextUrls) {
      try {
        const response = await fetch(url, { credentials: "omit", headers: { Accept: "application/json, text/xml, */*" } });
        if (!response.ok) {
          lastError = new Error("YouTube から字幕本文を取得できませんでした。");
          continue;
        }
        const snippets = await snippetsFromTimedTextBody(await response.text());
        if (!snippets.length) {
          lastError = new Error("日本語・英語の字幕が見つかりませんでした。");
          continue;
        }
        return {
          languageCode: selected.languageCode || languages[0] || "en",
          isGenerated: selected.kind === "asr",
          snippets,
          captionTracks: tracks,
        };
      } catch (err) {
        lastError = err;
      }
    }
    throw lastError instanceof Error ? lastError : new Error("日本語・英語の字幕が見つかりませんでした。");
  }

  function parseProxyPayload(rawText, videoId, languages) {
    const trimmed = String(rawText || "").trim();
    if (!trimmed) throw new Error("プロキシから空のレスポンスが返されました。");

    let data;
    try {
      data = JSON.parse(trimmed);
    } catch (_err) {
      if (trimmed.includes("WEBVTT") || trimmed.includes("-->")) {
        return parseVttTranscript(trimmed, videoId, languages);
      }
      throw new Error(`プロキシのレスポンスを解析できませんでした: ${trimmed.slice(0, 120)}`);
    }

    if (data?.ok === false || data?.error) {
      throw new Error(String(data.error || data.message || "字幕の取得に失敗しました。"));
    }

    if (
      typeof data?.language_code === "string" &&
      Array.isArray(data?.snippets) &&
      data.snippets.length
    ) {
      return {
        languageCode: data.language_code,
        isGenerated: Boolean(data.is_generated),
        snippets: normalizeSnippets(data.snippets),
      };
    }

    if (Array.isArray(data?.snippets) && data.snippets.length) {
      return {
        languageCode: data.language_code || data.languageCode || "en",
        isGenerated: Boolean(data.is_generated ?? data.isGenerated ?? data.isAutoGenerated),
        snippets: normalizeSnippets(data.snippets),
      };
    }

    if (Array.isArray(data?.segments) && data.segments.length) {
      return {
        languageCode: data.language_code || data.languageCode || data.language || "en",
        isGenerated: Boolean(data.is_generated ?? data.isGenerated ?? data.kind === "asr"),
        snippets: normalizeSnippets(data.segments),
      };
    }

    if (Array.isArray(data?.transcript) && data.transcript.length) {
      return {
        languageCode: data.language_code || data.languageCode || data.language || "en",
        isGenerated: Boolean(data.is_generated ?? data.isGenerated),
        snippets: normalizeSnippets(data.transcript),
      };
    }

    if (Array.isArray(data) && data.length) {
      return {
        languageCode: "en",
        isGenerated: false,
        snippets: normalizeSnippets(data),
      };
    }

    if (data?.events) {
      const snippets = parseTimedTextEvents(data);
      if (!snippets.length) throw new Error("字幕データを解析できませんでした。");
      return {
        languageCode: data.language_code || data.languageCode || data.language || "en",
        isGenerated: Boolean(data.is_generated ?? data.isGenerated ?? data.kind === "asr"),
        snippets,
      };
    }

    if (data?.subtitles) {
      const picked = pickScrapingBeeTrack(data.subtitles, languages);
      if (!picked?.snippets?.length) throw new Error("日本語・英語の字幕が見つかりませんでした。");
      return picked;
    }

    const tracks =
      data?.caption_tracks ||
      data?.captionTracks ||
      data?.captions?.playerCaptionsTracklistRenderer?.captionTracks ||
      data?.tracks;
    if (Array.isArray(tracks) && tracks.length) {
      const selected = selectCaptionTrack(tracks, languages, true);
      const snippets = parseCaptionTrackEvents(selected);
      if (!snippets.length && selected?.baseUrl && data?.events) {
        return {
          languageCode: selected.languageCode || data.language_code || "en",
          isGenerated: selected.kind === "asr" || Boolean(data.is_generated),
          snippets: parseTimedTextEvents(data),
          captionTracks: tracks,
        };
      }
      return {
        languageCode: selected?.languageCode || data.language_code || "en",
        isGenerated: selected?.kind === "asr" || Boolean(data.is_generated ?? data.isGenerated),
        snippets,
        captionTracks: tracks,
      };
    }

    if (typeof data?.text === "string" && data.text.trim()) {
      return {
        languageCode: data.language_code || data.languageCode || data.language || "en",
        isGenerated: Boolean(data.is_generated ?? data.isGenerated),
        snippets: [{ start: 0, duration: 0.1, text: data.text.trim() }],
      };
    }

    throw new Error("プロキシのレスポンス形式が未対応です。");
  }

  function parseVttTimestamp(value) {
    const raw = String(value || "").trim().replace(",", ".");
    const parts = raw.split(":");
    if (parts.length === 3) {
      return Number(parts[0]) * 3600 + Number(parts[1]) * 60 + Number(parts[2]);
    }
    if (parts.length === 2) {
      return Number(parts[0]) * 60 + Number(parts[1]);
    }
    return 0;
  }

  function parseVttTranscript(text, videoId, languages) {
    const snippets = [];
    const blocks = text.replace(/\r\n/g, "\n").split(/\n\s*\n/);
    for (const block of blocks) {
      const lines = block.split("\n").map((line) => line.trim()).filter(Boolean);
      const timeLine = lines.find((line) => line.includes("-->"));
      if (!timeLine) continue;
      const [startRaw, endRaw] = timeLine.split("-->").map((part) => part.trim());
      const start = parseVttTimestamp(startRaw);
      const end = parseVttTimestamp(endRaw.split(" ")[0]);
      const body = lines
        .filter((line) => line !== timeLine && !/^\d+$/.test(line))
        .join(" ")
        .replace(/<[^>]+>/g, " ")
        .replace(/\s+/g, " ")
        .trim();
      if (!body) continue;
      snippets.push({ start, duration: Math.max(end - start, 0.1), text: body });
    }
    if (!snippets.length) throw new Error("字幕データを解析できませんでした。");
    return {
      languageCode: languages[0] || "en",
      isGenerated: false,
      snippets: normalizeSnippets(snippets),
    };
  }

  function filterSnippetsByRange(snippets, startSec, endSec) {
    if (endSec <= startSec) return snippets;
    return snippets.filter((snippet) => {
      const snippetStart = Number(snippet.start || 0);
      const snippetEnd = snippetStart + Number(snippet.duration || 0);
      return snippetStart < endSec && snippetEnd > startSec;
    });
  }

  function formatTranscriptTimestamp(sec) {
    const s = Math.max(0, Math.floor(Number(sec) || 0));
    const hours = Math.floor(s / 3600);
    const minutes = Math.floor((s % 3600) / 60);
    const seconds = s % 60;
    if (hours) return `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
    return `${minutes}:${String(seconds).padStart(2, "0")}`;
  }

  function formatScriptForLesson(snippets) {
    const lines = [];
    let current = [];
    for (const snippet of snippets) {
      const text = String(snippet.text || "").trim();
      if (!text) continue;
      current.push(text);
      if (/[.!?]$/.test(text)) {
        lines.push(current.join(" "));
        current = [];
      }
    }
    if (current.length) lines.push(current.join(" "));
    return lines.join("\n");
  }

  function formatTimedScript(snippets) {
    return snippets
      .map((snippet) => `${formatTranscriptTimestamp(snippet.start)}  ${snippet.text}`)
      .join("\n");
  }

  function translateFetchError(err, statusCode) {
    const message = String(err?.message || err || "").toLowerCase();
    if (err instanceof TypeError || message.includes("failed to fetch") || message.includes("networkerror")) {
      return new Error(
        "字幕プロキシ（Cloudflare Workers）に接続できませんでした。Worker の URL とデプロイ状態を確認してください。"
      );
    }
    if (statusCode === 404 || message.includes("not found")) {
      return new Error("動画が見つからないか、再生できません。");
    }
    if (statusCode === 429 || message.includes("429") || message.includes("rate limit")) {
      return new Error("YouTube へのリクエストが制限されています。しばらく待ってから再試行してください。");
    }
    if (message.includes("blocked") || message.includes("sign in to confirm")) {
      return new Error("YouTube から字幕を取得できませんでした。動画が非公開・年齢制限の可能性があります。");
    }
    if (message.includes("no captions") || message.includes("字幕")) {
      return err instanceof Error ? err : new Error(String(err || "字幕の取得に失敗しました。"));
    }
    return err instanceof Error ? err : new Error(String(err || "字幕の取得に失敗しました。"));
  }

  async function withTimeout(timeoutMs, operation) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    try {
      return await operation(controller.signal);
    } finally {
      clearTimeout(timer);
    }
  }

  async function fetchWithRetry(url, baseOptions, maxRetries, timeoutMs) {
    let lastError = null;
    let lastResponse = null;
    for (let attempt = 0; attempt < maxRetries; attempt += 1) {
      try {
        const response = await withTimeout(timeoutMs, (signal) =>
          fetch(url, { ...baseOptions, signal })
        );
        lastResponse = response;
        const retryable = [408, 425, 429, 500, 502, 503, 504].includes(response.status);
        if (retryable && attempt < maxRetries - 1) {
          const delayMs = response.status === 429 ? 4000 * (attempt + 1) : 2 ** attempt * 1000;
          await new Promise((resolve) => setTimeout(resolve, delayMs));
          continue;
        }
        return response;
      } catch (err) {
        lastError = err;
        if (attempt >= maxRetries - 1) break;
        await new Promise((resolve) => setTimeout(resolve, 2 ** attempt * 1000));
      }
    }
    if (lastResponse) return lastResponse;
    throw translateFetchError(lastError || new Error("字幕の取得に失敗しました。"));
  }

  async function readTranscriptResponse(response) {
    const body = await response.text();
    if (!response.ok) {
      try {
        const errJson = JSON.parse(body);
        throw new Error(String(errJson.error || errJson.message || `HTTP ${response.status}`));
      } catch (err) {
        if (err instanceof Error && err.message && !err.message.startsWith("Unexpected")) throw err;
        throw translateFetchError(new Error(body.slice(0, 200) || `HTTP ${response.status}`), response.status);
      }
    }
    return body;
  }

  async function fetchTranscriptFromUrl(url, languages, timeoutMs, maxRetries) {
    const response = await fetchWithRetry(
      url,
      { headers: { Accept: "application/json, text/plain, */*" } },
      maxRetries,
      timeoutMs
    );
    const body = await readTranscriptResponse(response);
    return parseProxyPayload(body, "", languages);
  }

  function readLocalTranscriptCache(videoId) {
    try {
      const raw = global.localStorage?.getItem(`${LOCAL_CACHE_PREFIX}${videoId}`);
      if (!raw) return null;
      const data = JSON.parse(raw);
      if (!data?.savedAt || Date.now() - Number(data.savedAt) > LOCAL_CACHE_TTL_MS) return null;
      if (!Array.isArray(data.snippets) || !data.snippets.length) return null;
      return data;
    } catch (_err) {
      return null;
    }
  }

  function writeLocalTranscriptCache(videoId, parsed) {
    try {
      global.localStorage?.setItem(
        `${LOCAL_CACHE_PREFIX}${videoId}`,
        JSON.stringify({
          savedAt: Date.now(),
          languageCode: parsed.languageCode,
          isGenerated: parsed.isGenerated,
          snippets: parsed.snippets,
        })
      );
    } catch (_err) {
      // quota / private mode
    }
  }

  function loadYouTubeIframeApi() {
    if (global.YT && global.YT.Player) return Promise.resolve();
    if (global.__vibeNewsYtApiReady) return global.__vibeNewsYtApiReady;
    global.__vibeNewsYtApiReady = new Promise((resolve) => {
      const previous = global.onYouTubeIframeAPIReady;
      global.onYouTubeIframeAPIReady = () => {
        if (typeof previous === "function") previous();
        resolve();
      };
      if (!document.querySelector('script[src="https://www.youtube.com/iframe_api"]')) {
        const script = document.createElement("script");
        script.src = "https://www.youtube.com/iframe_api";
        document.head.appendChild(script);
      }
      if (global.YT && global.YT.Player) resolve();
    });
    return global.__vibeNewsYtApiReady;
  }

  function tracksFromUnknownPayload(data) {
    if (!data) return [];
    if (Array.isArray(data.captionTracks)) return data.captionTracks;
    const nested =
      data.captions?.playerCaptionsTracklistRenderer?.captionTracks ||
      data.playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks ||
      data.response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ||
      data.info?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
    return Array.isArray(nested) ? nested : [];
  }

  function listenForEmbedCaptionTracks(timeoutMs) {
    return new Promise((resolve) => {
      let settled = false;
      const finish = (tracks) => {
        if (settled) return;
        settled = true;
        global.removeEventListener("message", onMessage);
        resolve(tracks || []);
      };
      const timer = setTimeout(() => finish([]), timeoutMs);
      function onMessage(event) {
        const origin = String(event.origin || "");
        if (!origin.includes("youtube.com")) return;
        let payload = event.data;
        if (typeof payload === "string") {
          try {
            payload = JSON.parse(payload);
          } catch (_err) {
            return;
          }
        }
        const tracks = tracksFromUnknownPayload(payload);
        if (tracks.length && tracks.some((track) => track.baseUrl || track.url)) {
          clearTimeout(timer);
          finish(tracks);
        }
      }
      global.addEventListener("message", onMessage);
    });
  }

  function publicTracksFromPlayerList(list) {
    return (list || [])
      .map((track) => ({
        languageCode: track.languageCode || track.language || "",
        kind: track.kind || (String(track.vssId || "").startsWith("a.") ? "asr" : ""),
        baseUrl: track.baseUrl || track.url || "",
      }))
      .filter((track) => track.baseUrl);
  }

  async function fetchCaptionTracksFromEmbed(videoId, timeoutMs) {
    if (!document.body) return [];
    await loadYouTubeIframeApi();
    const iframe = document.createElement("iframe");
    iframe.setAttribute("aria-hidden", "true");
    iframe.style.cssText = "position:absolute;width:1px;height:1px;left:-9999px;opacity:0;pointer-events:none";
    iframe.allow = "encrypted-media";
    iframe.src =
      `https://www.youtube.com/embed/${encodeURIComponent(videoId)}` +
      `?enablejsapi=1&rel=0&origin=${encodeURIComponent(global.location.origin)}`;
    document.body.appendChild(iframe);

    // 埋め込みプレイヤーは Worker/Render の両方がブロックされたときの最後の
    // 頼みの綱なので、他の候補より長めに待ってでも成功率を優先する。
    const embedTimeoutMs = Math.min(Math.max(timeoutMs, 12000), 15000);
    const messageTracksPromise = listenForEmbedCaptionTracks(embedTimeoutMs);
    const playerTracksPromise = new Promise((resolve) => {
      let finished = false;
      const done = (tracks) => {
        if (finished) return;
        finished = true;
        resolve(publicTracksFromPlayerList(tracks));
      };
      const timer = setTimeout(() => done([]), embedTimeoutMs);
      try {
        const player = new global.YT.Player(iframe, {
          events: {
            onReady: () => {
              try {
                if (typeof player.loadModule === "function") player.loadModule("captions");
              } catch (_err) {
                /* ignore */
              }
              try {
                // captions トラック一覧は再生が始まるまで空のことが多いので、
                // ミュートで少しだけ再生させて playerResponse を確定させる。
                if (typeof player.mute === "function") player.mute();
                if (typeof player.playVideo === "function") player.playVideo();
              } catch (_err) {
                /* ignore */
              }
              const tryRead = () => {
                try {
                  const optionTracks = typeof player.getOption === "function"
                    ? player.getOption("captions", "tracklist")
                    : [];
                  const info =
                    player.playerInfo?.playerResponse ||
                    player.playerInfo?.response ||
                    (typeof player.getPlayerResponse === "function" ? player.getPlayerResponse() : null);
                  const nested = tracksFromUnknownPayload(info);
                  const merged = [...(optionTracks || []), ...nested];
                  if (merged.length) {
                    clearTimeout(timer);
                    done(merged);
                    return true;
                  }
                } catch (_err) {
                  /* ignore */
                }
                return false;
              };
              // 1回で取れないことが多いので、間隔を空けながら数回リトライする。
              const retryDelaysMs = [600, 1500, 3000, 6000, 10000];
              retryDelaysMs.forEach((delay) => {
                if (delay < embedTimeoutMs) setTimeout(tryRead, delay);
              });
              tryRead();
            },
            onApiChange: () => {
              try {
                const optionTracks = player.getOption("captions", "tracklist") || [];
                if (optionTracks.length) {
                  clearTimeout(timer);
                  done(optionTracks);
                }
              } catch (_err) {
                /* ignore */
              }
            },
          },
        });
      } catch (_err) {
        clearTimeout(timer);
        done([]);
      }
    });

    try {
      const [messageTracks, playerTracks] = await Promise.all([messageTracksPromise, playerTracksPromise]);
      const merged = publicTracksFromPlayerList([...(playerTracks || []), ...(messageTracks || [])]);
      return merged;
    } finally {
      iframe.remove();
    }
  }

  async function tryUpgradeTracksWithBrowserBody(tracks, languages) {
    if (!tracks?.length) return null;
    try {
      const withBody = await fetchTimedTextInBrowser(tracks, languages);
      return withBody?.snippets?.length ? withBody : null;
    } catch (_err) {
      return null;
    }
  }

  async function fetchTranscriptFromProxy(videoId, languages, timeoutMs, maxRetries) {
    const urls = [
      `${PROXY_BASE_URL}?id=${encodeURIComponent(videoId)}`,
      `${SAME_ORIGIN_WORKER_RELAY_URL}?id=${encodeURIComponent(videoId)}`,
      `${SAME_ORIGIN_TRANSCRIPT_URL}?id=${encodeURIComponent(videoId)}`,
    ];

    let lastError = null;
    let tracksOnly = null;
    // Worker がすぐに本文まで返してくれる（多くの場合はこれで済む）間は埋め込み
    // プレイヤーを起動しない。Worker が失敗/トラックのみだった時点で初めて、
    // 埋め込みプレイヤー経由のトラック取得を裏で並行して走らせ、Render を試す
    // 待ち時間と重ねることで最終フォールバックの待ち時間を短縮する。
    let embedTracksPromise = null;

    for (const url of urls) {
      try {
        const isWorkerBacked = url.includes("workers.dev") || url.includes(SAME_ORIGIN_WORKER_RELAY_URL);
        const parsed = await fetchTranscriptFromUrl(url, languages, timeoutMs, isWorkerBacked ? maxRetries : 1);
        if (parsed?.snippets?.length) return parsed;
        if (parsed?.captionTracks?.length) {
          if (!tracksOnly) tracksOnly = parsed;
          if (!embedTracksPromise) {
            embedTracksPromise = fetchCaptionTracksFromEmbed(videoId, timeoutMs).catch(() => []);
          }
          const withBody = await tryUpgradeTracksWithBrowserBody(parsed.captionTracks, languages);
          if (withBody) return withBody;
        }
      } catch (err) {
        lastError = err;
        if (!embedTracksPromise) {
          embedTracksPromise = fetchCaptionTracksFromEmbed(videoId, timeoutMs).catch(() => []);
        }
      }
    }

    if (!embedTracksPromise) {
      embedTracksPromise = fetchCaptionTracksFromEmbed(videoId, timeoutMs).catch(() => []);
    }
    try {
      const embedTracks = await embedTracksPromise;
      if (embedTracks.length) {
        if (!tracksOnly) {
          tracksOnly = {
            languageCode: embedTracks[0].languageCode || languages[0] || "en",
            isGenerated: embedTracks[0].kind === "asr",
            snippets: [],
            captionTracks: embedTracks,
          };
        }
        const withBody = await tryUpgradeTracksWithBrowserBody(embedTracks, languages);
        if (withBody) return withBody;
      }
    } catch (err) {
      lastError = err;
    }

    if (tracksOnly?.captionTracks?.length) return tracksOnly;
    throw lastError instanceof Error ? lastError : new Error(String(lastError || "字幕の取得に失敗しました。"));
  }

  async function fetchTranscript(videoIdOrUrl, options) {
    const opts = options || {};
    const languages = opts.languages || DEFAULT_LANGUAGES;
    const timeoutMs = opts.timeoutMs || DEFAULT_TIMEOUT_MS;
    const maxRetries = opts.maxRetries || DEFAULT_MAX_RETRIES;
    const startSec = opts.startSec ?? null;
    const endSec = opts.endSec ?? null;

    const videoId = extractVideoId(videoIdOrUrl);
    let parsed = readLocalTranscriptCache(videoId);
    if (!parsed?.snippets?.length) {
      parsed = await fetchTranscriptFromProxy(videoId, languages, timeoutMs, maxRetries);
      if (!parsed?.snippets?.length && parsed?.captionTracks?.length) {
        parsed = await fetchTimedTextInBrowser(parsed.captionTracks, languages);
      }
      if (!parsed?.snippets?.length) {
        throw new Error("日本語・英語の字幕が見つかりませんでした。");
      }
      writeLocalTranscriptCache(videoId, parsed);
    }

    const fetchedSnippets = parsed.snippets;
    let snippets = fetchedSnippets;
    let rangeApplied = false;
    if (startSec !== null && endSec !== null && Number(endSec) > Number(startSec)) {
      snippets = filterSnippetsByRange(fetchedSnippets, Number(startSec), Number(endSec));
      rangeApplied = true;
      if (!snippets.length) {
        throw new Error("指定した時間範囲に文字起こしがありません。");
      }
    }

    const allSnippets = normalizeSnippets(fetchedSnippets);
    const activeSnippets = normalizeSnippets(snippets);

    return {
      video_id: videoId,
      language: languageLabel(parsed.languageCode),
      language_code: parsed.languageCode,
      is_generated: Boolean(parsed.isGenerated),
      script: formatScriptForLesson(activeSnippets),
      script_timed: formatTimedScript(activeSnippets),
      snippets: activeSnippets,
      all_snippets: rangeApplied ? allSnippets : activeSnippets,
      range_applied: rangeApplied,
      start_sec: rangeApplied ? Number(startSec) : null,
      end_sec: rangeApplied ? Number(endSec) : null,
    };
  }

  global.YoutubeTranscript = {
    extractVideoId,
    fetchTranscript,
    filterSnippetsByRange,
    formatScriptForLesson,
    formatTimedScript,
    normalizeSnippets,
  };
})(window);
